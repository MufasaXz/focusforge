"""Generate offline Flutter and Android display copy using the Python standard library."""
from pathlib import Path
import hashlib
import json
import re
import sys
import xml.etree.ElementTree as ET

check = '--check' in sys.argv
def write(path, content):
    if check:
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            raise ValueError(f'Generated copy is stale: {path.relative_to(root)}')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf-8')

root = Path(__file__).resolve().parents[1]
source = root/'localization'
locales = ['hi','bn','ur','ta','te','mr','gu','es','pt','fr','de','it','tr','ru','uk','ar','fa','id','ms','vi','th','ko','ja','zh']
native = json.loads((source/'native-translation-keys.json').read_text(encoding='utf-8'))
resources = root/'android/app/src/main/res'
resource_sources = json.loads((source/'android-resource-sources.json').read_text(encoding='utf-8'))
actual_sources = {e.attrib['name']: e.text or '' for e in ET.parse(resources/'values/strings.xml').getroot() if e.tag == 'string'}
if actual_sources != resource_sources:
    raise ValueError('Update localization/android-resource-sources.json to match values/strings.xml')
for text in resource_sources.values(): native[text] = text
catalog = json.loads((source/'catalog.json').read_text(encoding='utf-8'))
catalog.update(native)
bundles={}
for lang in locales:
    data=json.loads((source/'translations'/f'{lang}.json').read_text(encoding='utf-8'))
    if set(catalog) != set(data): raise ValueError(f'{lang} catalog keys differ from English')
    for key,value in data.items():
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f'Empty translation: {lang} {key}')
        if set(re.findall(r'\{\d+\}',key)) != set(re.findall(r'\{\d+\}',value)):
            raise ValueError(f'Invalid slots: {lang} {key}')
        if 'ZXQ' in value: raise ValueError(f'Leaked marker {lang} {key}')
    bundles[lang]={k:data[k] for k in sorted(catalog)}

def dart(value):return json.dumps(value,ensure_ascii=False).replace('$',r'\$')
out=['// Generated by tool/generate_localizations.py. Edit localization/translations/*.json.','// Bundled display translations. No network translation is used at runtime.','const translations = <String, Map<String, String>>{']
for lang,data in bundles.items():
    out.append('  '+dart(lang)+': {')
    out += ['    '+dart(k)+': '+dart(v)+',' for k,v in data.items()]
    out.append('  },')
out.append('};')
write(root/'lib/core/localization/translations.dart', '\n'.join(out)+'\n')

ids={s:'ff_copy_'+hashlib.sha256(s.encode()).hexdigest()[:12] for s in native}
def android_text(value):
    slash = chr(92)
    return value.replace(slash,slash*2).replace("'",slash+"'").replace('"',slash+'"').replace(chr(10),slash+'n').replace('@',slash+'@').replace('?',slash+'?')
for lang in ['en']+locales:
    tree=ET.Element('resources')
    data={} if lang=='en' else bundles[lang]
    for key,rid in ids.items():
        ET.SubElement(tree,'string',name=rid,formatted='false').text=android_text(data.get(key,key))
    # Android settings and XML layouts use stable resource identifiers.
    if lang!='en':
        for rid,key in resource_sources.items():
            ET.SubElement(tree,'string',name=rid,formatted='false').text=android_text(data[key])
    target=resources/('values' if lang=='en' else 'values-'+lang)
    ET.indent(tree)
    write(target/'localized_copy.xml', ET.tostring(tree,encoding='unicode',xml_declaration=True))

lines=['package dev.focusforge.focusforge.localization','','import android.content.Context','import dev.focusforge.focusforge.R','','/** Offline copy selected by Android from the phone language list. */','object DeviceStrings {','    private val resources = mapOf(']
lines += ['        '+json.dumps(k,ensure_ascii=False)+' to R.string.'+v+',' for k,v in ids.items()]
lines += ['    )',r'    private val slot = Regex("\\{(\\d+)\\}")','    fun text(context: Context, source: String, vararg values: Any?): String {','        val copy = resources[source]?.let { context.getString(it) } ?: source','        return slot.replace(copy) { match ->','            values.getOrNull(match.groupValues[1].toInt())?.toString() ?: match.value','        }','    }','','    fun reason(context: Context, source: String): String {',r'        val budget = Regex("You have used your (\\d+) minutes for today\\.").matchEntire(source)','        return if (budget != null) text(context, "You have used your {0} minutes for today.", budget.groupValues[1])','            else text(context, source)','    }','}']
p=root/'android/app/src/main/kotlin/dev/focusforge/focusforge/localization/DeviceStrings.kt'
write(p, '\n'.join(lines)+'\n')
print('Bundled',len(catalog),'keys in',len(locales)+1,'languages;',len(ids),'native keys')
